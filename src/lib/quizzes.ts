// Получить тест по id контента или вернуть универсальный
export function getQuizForContent(
  contentId: string,
  contentType: "post" | "podcast" | "article",
): MicroQuiz {
  const found = quizzes[contentId];
  if (found) return found;
  return {
    contentId,
    contentType,
    questions: universalQuiz.questions,
  };
}
